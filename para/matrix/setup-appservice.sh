#!/bin/bash
set -euo pipefail

# ═════════════════════════════════════════════════════════════════════════════
# PARA — matrix-bridge application service registration
#
# Writes, once, into deploy/matrix/synapse/ (gitignored):
#
#   para-bridge-registration.yaml   the appservice registration, with fresh
#                                   as_token / hs_token
#   zz-para-appservice.yaml         the overlay that makes Synapse load it
#
# MAS provisions accounts for derived MXIDs: localparts of exactly 32
# lowercase base32 characters (CD-M1, docs/MATRIX_V2.md §4;
# services/matrix-bridge/src/identity-proof.ts). The user namespace is
# nonexclusive: an exclusive reservation prevents MAS native registration.
# The trusted IdP forces the derived localpart; passwords and free registration
# stay disabled. The bridge observes these users but never pre-provisions them.
#
# Environment:
#   MATRIX_SERVER_NAME      default matrix.para.social
#   BRIDGE_APPSERVICE_URL   where Synapse pushes transactions. Default
#                           http://host.docker.internal:3001 (the local bridge
#                           runs on the host); the platform passes
#                           http://matrix-bridge:3001.
#
# Give the bridge the same tokens: MATRIX_APPSERVICE_TOKEN = as_token and
# MATRIX_HS_TOKEN = hs_token (the platform's `make secrets-import` copies
# them). Rotation: deploy/matrix/RUNBOOK_SECURITY_ES.md.
# ═════════════════════════════════════════════════════════════════════════════

# Writes into WatZappa's deploy/matrix, where its docker-compose.matrix.yaml
# mounts the generated config from (make matrix-init passes the path).
SCRIPT_DIR="${MATRIX_DEPLOY_DIR:?Define MATRIX_DEPLOY_DIR (WatZappa/deploy/matrix); run make matrix-init}"
SYNAPSE_DIR="${SCRIPT_DIR}/synapse"
REG="${SYNAPSE_DIR}/para-bridge-registration.yaml"
OVERLAY="${SYNAPSE_DIR}/zz-para-appservice.yaml"

MATRIX_SERVER_NAME="${MATRIX_SERVER_NAME:-matrix.para.social}"
BRIDGE_APPSERVICE_URL="${BRIDGE_APPSERVICE_URL:-http://host.docker.internal:3001}"

if [ ! -d "$SYNAPSE_DIR" ]; then
    echo "❌ ${SYNAPSE_DIR} not found. Run deploy/matrix/setup.sh first."
    exit 1
fi

if [ -f "$REG" ]; then
    if grep -q 'exclusive: true' "$REG"; then
        echo 'Existing exclusive appservice reservation blocks MAS native registration.' >&2
        echo 'Review existing appservice accounts before updating this registration; see docs/CHAT-STAGING.md.' >&2
        exit 2
    fi
    echo "⚠️  ${REG} already exists; leaving it (and its tokens) alone."
else
    # Regex-escape the dots of the server name; single-quoted YAML keeps the
    # backslashes literal.
    SERVER_RE="$(printf '%s' "$MATRIX_SERVER_NAME" | sed 's/\./\\./g')"
    umask 077
    cat > "$REG" <<REGEOF
# GENERATED by deploy/matrix/setup-appservice.sh — contains secrets, do not commit.
#
# PARA bridge observes derived MXIDs; MAS creates native accounts after IdP
# approval. Do not reserve these names exclusively or pre-provision them.
id: para-bridge
url: ${BRIDGE_APPSERVICE_URL}
as_token: $(openssl rand -hex 32)
hs_token: $(openssl rand -hex 32)
rate_limited: false
sender_localpart: para-bridge
namespaces:
  users:
    # 32 lowercase base32 characters, on this homeserver only.
    - regex: '@[a-z2-7]{32}:${SERVER_RE}\$'
      exclusive: false
  rooms: []
  aliases: []
REGEOF
    echo "✅ ${REG}"
fi

if [ ! -f "$OVERLAY" ]; then
    cat > "$OVERLAY" <<OVEOF
# GENERATED by deploy/matrix/setup-appservice.sh.
# Makes Synapse load the PARA bridge appservice registration next to it.
app_service_config_files:
  - /config/para-bridge-registration.yaml
OVEOF
    echo "✅ ${OVERLAY}"
fi
